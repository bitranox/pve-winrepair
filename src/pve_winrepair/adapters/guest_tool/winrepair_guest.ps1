$PwshPyAncestorWriteRights = 0x40 -bor 0x10000 -bor 0x40000 -bor 0x80000 -bor 0x10000000
# POSIX: the accounts trusted to own what root runs, by uid: root alone.
$PwshPyTrustedUids = @('0')
